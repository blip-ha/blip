// Writes custom_components/blip/frontend/blip-icons.js after `vite build`: a tiny module the
// integration loads on every Home Assistant page so the sidebar can show the Blip mark
// (icon "blip:mark"). Generated; rebuilt by `npm run build`.
import { writeFileSync } from "node:fs";
import { MARK } from "../src/sidebar-icon.ts";

export function iconsModule(): string {
  return `// Generated by frontend/scripts/bundle-icons.ts. Don't edit by hand.
// Registers the "blip:" icon set used for Blip's sidebar entry.
const ICONS = { mark: ${JSON.stringify(MARK)} };
window.customIcons = window.customIcons || {};
window.customIcons.blip = {
  getIcon: async (name) => ICONS[name] ?? ICONS.mark,
  getIconList: async () => Object.keys(ICONS).map((name) => ({ name })),
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../../custom_components/blip/frontend/blip-icons.js", import.meta.url), iconsModule());
  console.log("wrote custom_components/blip/frontend/blip-icons.js");
}
